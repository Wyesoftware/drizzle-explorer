/**
 * Production build:
 *   1. vite build            -> dist/ui
 *   2. generate asset module -> src/main/assets.generated.ts (embeds dist/ui into the binary)
 *   3. bun build --compile   -> dist/bin/drizzle-explorer[.exe]
 *   4. on macOS: wrap into dist/Drizzle Explorer.app
 *
 * Usage: bun run build [--target bun-darwin-arm64|bun-linux-x64|bun-windows-x64|...] [--no-app] [--sign]
 *   --sign  (macOS) code-sign the .app with scripts/macos-sign.sh after bundling; picks the best local
 *           identity (Developer ID → Apple Development → ad-hoc). The release workflow signs separately.
 */
import { readdir, mkdir, rm, writeFile, chmod, copyFile } from "node:fs/promises";
import { join, relative, posix } from "node:path";
import { spawn } from "bun";

const root = new URL("..", import.meta.url).pathname;
const argv = process.argv.slice(2);
const targetIndex = argv.indexOf("--target");
const target = targetIndex >= 0 ? argv[targetIndex + 1] : undefined;
const makeApp = !argv.includes("--no-app") && (target ? target.includes("darwin") : process.platform === "darwin");
const isWindows = target ? target.includes("windows") : process.platform === "win32";
const signApp = argv.includes("--sign") && process.platform === "darwin";

const distUi = join(root, "dist/ui");
const binDir = join(root, "dist/bin");
const generated = join(root, "src/main/assets.generated.ts");
const binaryName = isWindows ? "drizzle-explorer.exe" : "drizzle-explorer";
const version = ((await Bun.file(join(root, "package.json")).json()) as { version: string }).version;

await run(["bunx", "vite", "build"]);

// Generate an import manifest so Bun embeds every built asset into the executable.
const files = await walk(distUi);
const lines = [
  "// AUTO-GENERATED by scripts/build.ts — do not edit, do not commit.",
  ...files.map((f, i) => `import a${i} from "../../dist/ui/${f}" with { type: "file" };`),
  "",
  "export const assets: Record<string, string> = {",
  ...files.map((f, i) => `  ${JSON.stringify("/" + f)}: a${i},`),
  "};",
  "",
];
const placeholder = await Bun.file(generated).text();
await writeFile(generated, lines.join("\n"));

await mkdir(binDir, { recursive: true });
const outfile = join(binDir, binaryName);
try {
await run([
  "bun",
  "build",
  "--compile",
  "--minify",
  "--sourcemap",
  `--define=DRIZZLE_EXPLORER_BUILD=${JSON.stringify(new Date().toISOString())}`,
  ...(target ? [`--target=${target}`] : []),
  ...(isWindows ? ["--windows-hide-console"] : []),
  "src/main/index.ts",
  "src/main/worker.ts",
  "--outfile",
  outfile,
]);
} finally {
  await writeFile(generated, placeholder);
}
console.log(`\n✔ Executable: ${relative(root, outfile)}`);

if (makeApp) {
  const appName = "Drizzle Explorer";
  const appDir = join(root, "dist", `${appName}.app`);
  const macos = join(appDir, "Contents/MacOS");
  const resources = join(appDir, "Contents/Resources");
  await rm(appDir, { recursive: true, force: true });
  await mkdir(macos, { recursive: true });
  await mkdir(resources, { recursive: true });
  await copyFile(outfile, join(macos, "drizzle-explorer"));
  await chmod(join(macos, "drizzle-explorer"), 0o755);
  // App icon: generated from assets/icon.svg by scripts/make-icon.ts and committed.
  await copyFile(join(root, "assets/AppIcon.icns"), join(resources, "AppIcon.icns"));
  await writeFile(
    join(appDir, "Contents/Info.plist"),
    `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>${appName}</string>
  <key>CFBundleDisplayName</key><string>${appName}</string>
  <key>CFBundleIdentifier</key><string>com.wyesoftware.drizzle-explorer</string>
  <key>CFBundleVersion</key><string>${version}</string>
  <key>CFBundleShortVersionString</key><string>${version}</string>
  <key>LSApplicationCategoryType</key><string>public.app-category.developer-tools</string>
  <key>CFBundleExecutable</key><string>drizzle-explorer</string>
  <key>CFBundleIconFile</key><string>AppIcon</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>LSMinimumSystemVersion</key><string>12.0</string>
  <key>NSHighResolutionCapable</key><true/>
  <key>NSAppTransportSecurity</key><dict><key>NSAllowsLocalNetworking</key><true/></dict>
</dict>
</plist>
`,
  );
  console.log(`✔ App bundle: ${relative(root, appDir)}`);
  if (signApp) await run(["bash", join(root, "scripts/macos-sign.sh"), "sign", appDir]);
}

async function run(cmd: string[]): Promise<void> {
  console.log(`$ ${cmd.join(" ")}`);
  const proc = spawn(cmd, { cwd: root, stdout: "inherit", stderr: "inherit", env: process.env });
  const code = await proc.exited;
  if (code !== 0) {
    console.error(`Command failed with exit code ${code}`);
    process.exit(code);
  }
}

async function walk(dir: string, base = dir): Promise<string[]> {
  const entries = await readdir(dir, { withFileTypes: true });
  const out: string[] = [];
  for (const entry of entries) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await walk(full, base)));
    else if (entry.isFile()) out.push(relative(base, full).split("\\").join(posix.sep));
  }
  return out.sort();
}
